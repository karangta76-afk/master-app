// Master Service Icon Component with Custom Gradient Containers
export function TradeServiceIcon({ service = "", className = "w-6 h-6" }: { service?: string; className?: string }) {
  const norm = (service || "").toLowerCase();
  
  if (norm.includes("electr") || norm.includes("wiring")) {
    return <BoltIcon className={className} />;
  }
  if (norm.includes("plumb") || norm.includes("tap") || norm.includes("pipe") || norm.includes("water") || norm.includes("ro")) {
    return <WrenchIcon className={className} />;
  }
  if (norm.includes("ac") || norm.includes("cool") || norm.includes("refrigerat")) {
    return <SnowflakeIcon className={className} />;
  }
  if (norm.includes("paint")) {
    return <PaintRollerIcon className={className} />;
  }
  if (norm.includes("carpent") || norm.includes("wood") || norm.includes("furnitur")) {
    return <HammerIcon className={className} />;
  }
  if (norm.includes("clean") || norm.includes("maid") || norm.includes("housekeep")) {
    return <SparkleBroomIcon className={className} />;
  }
  if (norm.includes("appliance") || norm.includes("washing") || norm.includes("tv")) {
    return <PlugIcon className={className} />;
  }
  // Fallback generic trade
  return <WrenchIcon className={className} />;
}

export function TradeBadgeContainer({ 
  service,
  serviceName,
  children,
  size = "md"
}: { 
  service?: string;
  serviceName?: string;
  children?: React.ReactNode;
  size?: "sm" | "md" | "lg"
}) {
  const resolvedService = service || serviceName || "";
  const norm = resolvedService.toLowerCase();
  
  let bgStyles = "bg-gradient-to-br from-blue-500 to-indigo-600 text-white shadow-blue-500/20";
  
  if (norm.includes("electr")) {
    bgStyles = "bg-gradient-to-br from-amber-500 to-orange-600 text-white shadow-amber-500/25";
  } else if (norm.includes("plumb")) {
    bgStyles = "bg-gradient-to-br from-cyan-500 to-blue-600 text-white shadow-cyan-500/25";
  } else if (norm.includes("ac")) {
    bgStyles = "bg-gradient-to-br from-sky-400 to-indigo-600 text-white shadow-sky-500/25";
  } else if (norm.includes("paint")) {
    bgStyles = "bg-gradient-to-br from-violet-500 to-purple-700 text-white shadow-violet-500/25";
  } else if (norm.includes("carpent")) {
    bgStyles = "bg-gradient-to-br from-emerald-600 to-teal-700 text-white shadow-emerald-500/25";
  } else if (norm.includes("clean")) {
    bgStyles = "bg-gradient-to-br from-teal-400 to-emerald-600 text-white shadow-teal-500/25";
  } else if (norm.includes("appliance")) {
    bgStyles = "bg-gradient-to-br from-indigo-500 to-blue-700 text-white shadow-indigo-500/25";
  }

  const sizeStyles = size === "sm" 
    ? "w-9 h-9 rounded-xl p-2 text-sm shadow-sm" 
    : size === "lg" 
    ? "w-16 h-16 rounded-2xl p-4 text-2xl shadow-lg" 
    : "w-12 h-12 rounded-xl p-3 text-lg shadow-md";

  return (
    <div className={`flex items-center justify-center shrink-0 ${sizeStyles} ${bgStyles}`}>
      {children || <TradeServiceIcon service={resolvedService} className="w-full h-full" />}
    </div>
  );
}

